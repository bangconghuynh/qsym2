/// Structure to manage symmetry orbits (*i.e.* orbits generated by symmetry groups) of
/// multi-determinantal wavefunctions.
#[derive(Builder, Clone)]
pub struct MultiDeterminantsSymmetryOrbit<'a, 'g, G, T, B, SC>
where
    G: SymmetryGroupProperties,
    T: ComplexFloat + fmt::Debug + Lapack,
    SC: StructureConstraint + Hash + Eq + fmt::Display,
    B: 'a + Basis<Item = SlaterDeterminant<'a, T, SC>> + Clone,
    MultiDeterminants<'a, T, B, SC>: SymmetryTransformable,
{
    /// The generating symmetry group.
    group: &'g G,

    /// The origin multi-determinantal wavefunction of the orbit.
    origin: &'a MultiDeterminants<'a, T, B, SC>,

    /// The threshold for determining zero eigenvalues in the orbit overlap matrix.
    linear_independence_threshold: <T as ComplexFloat>::Real,

    // /// The threshold for determining if calculated multiplicities in representation analysis are
    // /// integral.
    // integrality_threshold: <T as ComplexFloat>::Real,
    /// The kind of transformation determining the way the symmetry operations in `group` act on
    /// [`Self::origin`].
    symmetry_transformation_kind: SymmetryTransformationKind,

    /// The overlap matrices between the corresponding symmetry-equivalent multi-eterminantal
    /// wavefunctions in their respective orbits.
    #[builder(setter(skip), default = "None")]
    smats: Option<Array3<T>>,
    // /// An enumerated type specifying the comparison mode for filtering out orbit overlap
    // /// eigenvalues.
    // eigenvalue_comparison_mode: EigenvalueComparisonMode,
}

// ----------------------------
// Struct method implementation
// ----------------------------

impl<'a, 'g, G, T, B, SC> MultiDeterminantsSymmetryOrbit<'a, 'g, G, T, B, SC>
where
    G: SymmetryGroupProperties + Clone,
    T: ComplexFloat + fmt::Debug + Lapack,
    SC: StructureConstraint + Hash + Eq + Clone + fmt::Display,
    B: 'a + Basis<Item = SlaterDeterminant<'a, T, SC>> + Clone,
    MultiDeterminants<'a, T, B, SC>: SymmetryTransformable,
{
    /// Returns a builder for constructing a new multi-determinantal wavefunction symmetry orbit.
    pub fn builder() -> MultiDeterminantsSymmetryOrbitBuilder<'a, 'g, G, T, B, SC> {
        MultiDeterminantsSymmetryOrbitBuilder::default()
    }

    /// Returns the origin of the multi-determinantal wavefunction symmetry orbit.
    pub fn origin(&self) -> &MultiDeterminants<'a, T, B, SC> {
        self.origin
    }

    pub fn smats(&self) -> Option<&Array3<T>> {
        self.smats.as_ref()
    }

    pub fn norm_preserving_scalar_map(&self, i: usize) -> Result<fn(T) -> T, anyhow::Error> {
        if self.origin.complex_symmetric {
            Err(format_err!(
                "`norm_preserving_scalar_map` is currently not implemented for complex-symmetric overlaps. This thus precludes the use of the Cayley table to speed up the computation of the orbit overlap matrix."
            ))
        } else if self
            .group
            .get_index(i)
            .unwrap_or_else(|| panic!("Group operation index `{i}` not found."))
            .contains_time_reversal()
        {
            Ok(ComplexFloat::conj)
        } else {
            Ok(|x| x)
        }
    }
}

