/// Structure to manage symmetry orbits (*i.e.* orbits generated by symmetry groups) of
/// a multi-determinantal wavefunction collection.
#[derive(Builder, Clone)]
pub struct MultiDeterminantsSymmetryOrbit<'a, 'g, G, T, B, SC>
where
    G: SymmetryGroupProperties,
    T: ComplexFloat + fmt::Debug + Lapack,
    SC: StructureConstraint + Hash + Eq + fmt::Display,
    B: 'a + Basis<Item = SlaterDeterminant<'a, T, SC>> + Clone,
    MultiDeterminants<'a, T, B, SC>: SymmetryTransformable,
{
    /// The generating symmetry group.
    group: &'g G,

    /// The origin multi-determinantal wavefunction collection of the orbit.
    origin: &'a MultiDeterminants<'a, T, B, SC>,

    /// The threshold for checking the symmetry of orbit overlap matrices.
    linear_independence_threshold: <T as ComplexFloat>::Real,

    /// The kind of transformation determining the way the symmetry operations in `group` act on
    /// [`Self::origin`].
    symmetry_transformation_kind: SymmetryTransformationKind,

    /// The overlap matrices between the corresponding symmetry-equivalent multi-determinantal
    /// wavefunctions in their respective orbits. The elements of this rank-3 array are
    /// $`S_{Aij}`$, where $`A`$ indexes the multi-determinantal wavefunctions in
    /// [`Self::origin`], and $`i, j`$ index the elements of [`Self::group`].
    #[builder(setter(skip), default = "None")]
    smats: Option<Array3<T>>,
}

// ----------------------------
// Struct method implementation
// ----------------------------

impl<'a, 'g, G, T, B, SC> MultiDeterminantsSymmetryOrbit<'a, 'g, G, T, B, SC>
where
    G: SymmetryGroupProperties + Clone,
    T: ComplexFloat + fmt::Debug + Lapack,
    SC: StructureConstraint + Hash + Eq + Clone + fmt::Display,
    B: 'a + Basis<Item = SlaterDeterminant<'a, T, SC>> + Clone,
    MultiDeterminants<'a, T, B, SC>: SymmetryTransformable,
{
    /// Returns a builder for constructing a new symmetry orbit for this multi-determinantal
    /// wavefunction collection.
    pub fn builder() -> MultiDeterminantsSymmetryOrbitBuilder<'a, 'g, G, T, B, SC> {
        MultiDeterminantsSymmetryOrbitBuilder::default()
    }

    /// Returns the origin of the multi-determinantal wavefunction collection symmetry orbit.
    pub fn origin(&self) -> &MultiDeterminants<'a, T, B, SC> {
        self.origin
    }

    /// Returns the overlap matrices between the corresponding symmetry-equivalent
    /// multi-determinantal wavefunctions in their respective orbits.
    pub fn smats(&self) -> Option<&Array3<T>> {
        self.smats.as_ref()
    }

    /// Returns the norm-preserving scalar map $`f`$ for every element of the generating group
    /// defined by
    ///
    /// ```math
    ///     \langle \hat{\iota} \mathbf{v}_w, \hat{g}_i \mathbf{v}_x \rangle
    ///     = f \left( \langle \hat{\iota} \hat{g}_i^{-1} \mathbf{v}_w, \mathbf{v}_x \rangle \right).
    /// ```
    ///
    /// Typically, for $`\hat{\iota} = \mathrm{id}`$, if $`\hat{g}_i`$ is unitary, then $`f`$ is the
    /// identity, and if $`\hat{g}_i`$ is antiunitary, then $`f`$ is the complex-conjugation
    /// operation. Either way, the norm of the inner product is preserved.
    ///
    /// If the overlap between items is complex-symmetric (*i.e.* $`\hat{\iota} = \hat{\kappa}`$,
    /// see [`crate::analysis::Overlap::complex_symmetric`]), then this map is currently unsupported
    /// because it is currently unclear if the unitary and antiunitary symmetry operators in QSym²
    /// commute with $`\hat{\kappa}`$. This thus precludes the use of the Cayley table to speed up
    /// the computation of the orbit overlap matrix.
    pub fn norm_preserving_scalar_map(&self, i: usize) -> Result<fn(T) -> T, anyhow::Error> {
        if self.origin.complex_symmetric {
            Err(format_err!(
                "`norm_preserving_scalar_map` is currently not implemented for complex-symmetric overlaps. This thus precludes the use of the Cayley table to speed up the computation of the orbit overlap matrix."
            ))
        } else if self
            .group
            .get_index(i)
            .unwrap_or_else(|| panic!("Group operation index `{i}` not found."))
            .contains_time_reversal()
        {
            Ok(ComplexFloat::conj)
        } else {
            Ok(|x| x)
        }
    }
}

